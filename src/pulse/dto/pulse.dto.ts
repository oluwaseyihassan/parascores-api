import {
  IsBoolean,
  IsIn,
  IsNotEmpty,
  IsOptional,
  IsString,
  Length,
} from 'class-validator';
import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';

/** Fixed reaction set — no free text, no moderation surface. */
export const PULSE_EMOJIS = ['🔥', '❤️', '😱', '👏', '😢'] as const;

export class PulseReactionDto {
  @ApiProperty({ enum: PULSE_EMOJIS })
  @IsIn(PULSE_EMOJIS as unknown as string[])
  emoji: string;

  @ApiProperty({ description: 'Anonymous device id generated by the client' })
  @IsString()
  @Length(8, 64)
  deviceId: string;
}

export class CreateAnnouncementDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  @Length(1, 120)
  title: string;

  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  @Length(1, 1000)
  body: string;

  @ApiPropertyOptional({ description: 'Pin to the top of the feed' })
  @IsOptional()
  @IsBoolean()
  pinned?: boolean;
}
